#!/usr/bin/env python3
"""
dmx_scene.py -- compute and send DMX512 scene-select commands.

    python tools/dmx_scene.py 7                       # just print the values
    python tools/dmx_scene.py 7 --addr 1 --send /dev/tty.usbserial-X

Per the GC-6612Pro datasheet the controller listens on 13 DMX channels from
a base address set on the unit itself. Channel Add+6 selects which scene
file on the SD card plays, quantised at FOUR DMX VALUES PER SCENE:

    scene 1 -> 0..3      scene n -> (n-1)*4 .. (n-1)*4+3
    scene 2 -> 4..7      safe value: (n-1)*4 + 1  (middle of the band)

Give every controller the same base address and one command starts them all
together -- which is the synchronised start this project needs, without any
hand timing.

CAVEAT: the channel map is documented for the GC-6612Pro. Our units are
GC-6004. Same vendor, same file format, very likely the same protocol, but
untested. If nothing responds, sweep --addr.

SENDING requires a USB-to-RS485 adapter (not USB-to-Ethernet) and pyserial.
Wiring, per the datasheet: RJ45 pin1 = D+, pin2 = D-, pin7 = GND.

The break is generated by dropping to a low baud rate for one byte, which is
the usual trick for sending DMX from a plain UART. It works on most FTDI and
CH340 adapters; a dedicated DMX interface is more reliable if you need it.
"""

import argparse, sys, time

CH_BRIGHTNESS = 1      # Add+1
CH_RED = 2
CH_GREEN = 3
CH_BLUE = 4
CH_WHITE = 5
CH_SCENE = 6           # Add+6
CH_SPEED = 7
CH_STROBE = 8
CH_MIX_MODE = 9
CH_MIX_R, CH_MIX_G, CH_MIX_B = 10, 11, 12
CH_GROUPING = 13

MAX_SCENES = 64


def scene_value(scene):
    """Scene number (1-64) -> a safe DMX value on Add+6."""
    if not 1 <= scene <= MAX_SCENES:
        raise ValueError(f"scene must be 1..{MAX_SCENES}, got {scene}")
    return (scene - 1) * 4 + 1


def scene_from_value(v):
    return v // 4 + 1


def build_universe(scene, addr=1, brightness=255, speed=None, strobe=0,
                   rgb=(255, 255, 255)):
    """-> 513-byte DMX packet: start code 0x00 then 512 channel slots."""
    u = bytearray(513)                      # u[0] is the start code, 0x00
    def setch(offset, value):
        slot = addr + offset - 1            # Add+1 is the base address itself
        if 1 <= slot <= 512:
            u[slot] = max(0, min(255, int(value)))
    setch(CH_BRIGHTNESS, brightness)
    setch(CH_RED, rgb[0]); setch(CH_GREEN, rgb[1]); setch(CH_BLUE, rgb[2])
    setch(CH_SCENE, scene_value(scene))
    if speed is not None:
        setch(CH_SPEED, speed)
    setch(CH_STROBE, strobe)
    return bytes(u)


def send(port, packet, seconds=3.0, fps=40):
    try:
        import serial
    except ImportError:
        raise SystemExit("pyserial not installed:  pip install pyserial")
    ser = serial.Serial(port, 250000, bytesize=8, parity="N", stopbits=2)
    n = int(seconds * fps)
    try:
        for _ in range(n):
            # BREAK: most reliably done with the driver's break control;
            # fall back to a low-baud null byte if unsupported.
            try:
                ser.break_condition = True
                time.sleep(0.0001)
                ser.break_condition = False
            except Exception:
                ser.baudrate = 90000
                ser.write(b"\x00")
                ser.flush()
                ser.baudrate = 250000
            ser.write(packet)
            ser.flush()
            time.sleep(1.0 / fps)
    finally:
        ser.close()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("scene", type=int, help="scene number 1-64")
    ap.add_argument("--addr", type=int, default=1,
                    help="controller's DMX base address (default 1)")
    ap.add_argument("--brightness", type=int, default=255)
    ap.add_argument("--speed", type=int, default=None)
    ap.add_argument("--send", metavar="PORT",
                    help="serial port of a USB-RS485 adapter")
    ap.add_argument("--seconds", type=float, default=3.0)
    a = ap.parse_args()

    v = scene_value(a.scene)
    pkt = build_universe(a.scene, a.addr, a.brightness, a.speed)
    print(f"scene {a.scene}  ->  DMX channel {a.addr + CH_SCENE - 1} "
          f"= {v}   (band {(a.scene-1)*4}..{(a.scene-1)*4+3})")
    print(f"  brightness  ch {a.addr + CH_BRIGHTNESS - 1} = {a.brightness}")
    if a.speed is not None:
        print(f"  speed       ch {a.addr + CH_SPEED - 1} = {a.speed}")
    nz = [(i, pkt[i]) for i in range(1, 513) if pkt[i]]
    print(f"  non-zero slots: {nz}")

    if a.send:
        print(f"\nsending on {a.send} for {a.seconds}s ...")
        send(a.send, pkt, a.seconds)
        print("done. If nothing changed, try a different --addr, or swap the "
              "RS-485 A/B lines (harmless).")
    else:
        print("\n(no --send given; add --send /dev/tty.usbserial-XXX to "
              "transmit)")


if __name__ == "__main__":
    main()
